package io.github.jaeseongs95.sennard.service.migration;

import java.util.regex.Pattern;

import io.github.jaeseongs95.sennard.service.database.SqlBuilder.Database;

/**
 * The one place where the migration scripts' standard SQL is written the other way a product spells it. The scripts are ANSI SQL for PostgreSQL and every database that has the
 * standard's forms; this class holds the whole difference, and it is a difference of spelling in two phrases, not of structure:
 *
 * <ul>
 * <li>{@code GENERATED BY DEFAULT AS IDENTITY}: MariaDB and MySQL have no identity column; their auto-increment column is the same thing ({@code AUTO_INCREMENT}: a key the database
 * makes, which the JDBC generated-keys API returns).</li>
 * <li>{@code TIMESTAMP}: the standard's time without a zone, to the millisecond, holding the UTC fields the service wrote (Timestamps in sennard-domain). MariaDB's and MySQL's
 * {@code TIMESTAMP} is another type (an instant stored as UTC and shown in the session's zone, from 1970-01-01 00:00:01 to 2038, without fractions unless asked), which would move the
 * value of a zone with a daylight-saving gap and refuse the epoch. Their {@code DATETIME(3)} is the standard's {@code TIMESTAMP(3)}.</li>
 * </ul>
 *
 * The digest of a script is that of the file as it is in the jar, whatever this class makes of it for a database.
 */
enum ScriptDialect {
    /** The standard's forms as the scripts write them (PostgreSQL, H2, Oracle, Db2, SQL Server as far as Sennard is known to run on them). */
    STANDARD {
        @Override
        String translate(String script) {
            return script;
        }
    },
    /** MariaDB and MySQL. */
    AUTO_INCREMENT_AND_DATETIME {
        @Override
        String translate(String script) {
            return TIMESTAMP_TYPE.matcher(IDENTITY.matcher(script).replaceAll("AUTO_INCREMENT")).replaceAll("DATETIME(3)");
        }
    };

    private static final Pattern IDENTITY = Pattern.compile("GENERATED\\s+BY\\s+DEFAULT\\s+AS\\s+IDENTITY");
    /** The word TIMESTAMP alone: not CURRENT_TIMESTAMP, not TIMESTAMP(3). */
    private static final Pattern TIMESTAMP_TYPE = Pattern.compile("(?<![A-Za-z0-9_])TIMESTAMP(?![A-Za-z0-9_(])");

    /** The script as the database takes it. */
    abstract String translate(String script);

    /** The spelling of a product. */
    static ScriptDialect of(Database product) {
        return switch (product) {
            case MARIADB, MYSQL -> AUTO_INCREMENT_AND_DATETIME;
            case H2, POSTGRESQL, ORACLE, DB2, SQLSERVER -> STANDARD;
        };
    }
}
