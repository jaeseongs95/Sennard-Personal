package io.github.jaeseongs95.sennard.repotools;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import io.github.jaeseongs95.sennard.server.hook.HostDefinition;
import io.github.jaeseongs95.sennard.server.hook.HostDefinitions;
import io.github.jaeseongs95.sennard.server.hook.ClientHookRegistration;
import io.github.jaeseongs95.sennard.server.hook.HostRegistrationFile;

/**
 * The files each plugin package ships ({@link ClientHookRegistration#shippedFiles()}): the hook definition and the MCP registration with nothing registered, generated by the same adapter that
 * answers the hooks. A package cannot hold a definition that works: the server has no port of its own choosing (the operating system gives one at each start), so a definition names the
 * program that finds it, and that program is the installation's own (its Java, its jar, the file where its server announces the address). {@code install}, {@code upgrade} and
 * {@code hooks} write the installation's files over the installed package's copy.
 *
 * <p>The hosts are not listed here: the tool has no Spring context, so it finds every {@link HostDefinition} the way the JDK finds implementations without a
 * container ({@link HostDefinitions}), and a host added to the product has its definition generated without a change here.
 */
public final class HostHookFiles {
    private final Repo repo;
    private final HostDefinitions hosts;

    public HostHookFiles(Repo repo) {
        this(repo, HostDefinitions.load());
    }

    /** The hosts given, not the ones the class path names: for a test that adds a host of its own. */
    public HostHookFiles(Repo repo, HostDefinitions hosts) {
        this.repo = repo;
        this.hosts = hosts;
    }

    /** The files by their path from the repository's root, in the order of the path. */
    public Map<String, String> render() {
        Map<String, String> files = new TreeMap<>();
        for (HostDefinition host : hosts.all()) {
            ClientHookRegistration adapter = host.hookAdapter(Repo.JSON);
            for (HostRegistrationFile.WholeFile shipped : adapter.shippedFiles()) {
                String path = Repo.posix(Path.of(host.packageDirectory()).resolve(shipped.relativePath()));
                if (files.put(path, PrettyJson.text(shipped.content())) != null) {
                    throw new IllegalStateException("Two hosts ship their definition at " + path);
                }
            }
        }
        return files;
    }

    public void write() {
        render().forEach(repo::write);
    }

    public List<String> check() {
        List<String> problems = new ArrayList<>();
        render().forEach((file, content) -> {
            if (!repo.exists(file) || !repo.text(file).equals(content)) {
                problems.add("stale file " + file);
            }
        });
        return problems;
    }
}
