-- V7: continuity. memory_json stays text: the digest is over its exact bytes.
-- A yes-or-no fact is a name that says what it means, listed in a CHECK: injection (ALLOWED or SUPPRESSED), pending_marker (OPEN or CONSUMED) and an observation's outcome
-- (SUCCEEDED or FAILED), each the constant's name of a Java enum, as the other state columns are. No column has a truth-value type (the standard has it as an optional feature)
-- and none holds 0 and 1 for it.
CREATE TABLE sennard.continuity_metadata (
    meta_key VARCHAR(255) NOT NULL, -- not named key: KEY is a reserved word of MariaDB and MySQL
    value ${long_text} NOT NULL,
    PRIMARY KEY (meta_key)
);

CREATE TABLE sennard.continuity_tasks (
    task_correlation VARCHAR(255) NOT NULL,
    current_epoch BIGINT NOT NULL,
    root_id VARCHAR(255),
    injection VARCHAR(16) DEFAULT 'ALLOWED' NOT NULL,
    last_auto_injected_revision BIGINT,
    pending_source VARCHAR(16), -- ContextSource: the enum constant's name
    pending_revision BIGINT,
    pending_digest VARCHAR(255),
    pending_root_id VARCHAR(255),
    pending_marker VARCHAR(16) DEFAULT 'OPEN' NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    pending_state_token VARCHAR(255),
    turn_asked_start BIGINT, -- the observation id of the start of the turn that the server has already asked the question for (TurnCheckService)
    PRIMARY KEY (task_correlation),
    CONSTRAINT continuity_tasks_epoch CHECK (current_epoch >= 1),
    CONSTRAINT continuity_tasks_injection CHECK (injection IN ('ALLOWED', 'SUPPRESSED')),
    CONSTRAINT continuity_tasks_pending_source CHECK (pending_source IN ('DIRECT', 'WORKFLOW')),
    CONSTRAINT continuity_tasks_pending_marker CHECK (pending_marker IN ('OPEN', 'CONSUMED'))
);
CREATE INDEX continuity_tasks_cleanup ON sennard.continuity_tasks (updated_at, task_correlation);

-- memory_json is at most 2000 bytes (a VARCHAR of 2000 characters holds that, and the CHECK counts the bytes); it is NULL or has its digest.
CREATE TABLE sennard.continuity_current_memory (
    task_correlation VARCHAR(255) NOT NULL,
    epoch BIGINT NOT NULL,
    state_token VARCHAR(255) NOT NULL,
    memory_json VARCHAR(2000),
    memory_digest VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (task_correlation),
    CONSTRAINT continuity_current_memory_epoch CHECK (epoch >= 1),
    CONSTRAINT continuity_current_memory_digest CHECK ((memory_json IS NULL AND memory_digest IS NULL) OR (memory_json IS NOT NULL AND memory_digest IS NOT NULL)),
    CONSTRAINT continuity_current_memory_size CHECK (memory_json IS NULL OR OCTET_LENGTH(memory_json) <= 2000)
);
CREATE INDEX continuity_current_memory_cleanup ON sennard.continuity_current_memory (updated_at, task_correlation);

CREATE TABLE sennard.continuity_memory_history (
    task_correlation VARCHAR(255) NOT NULL,
    state_token VARCHAR(255) NOT NULL,
    epoch BIGINT NOT NULL,
    memory_json ${long_text} NOT NULL,
    memory_digest VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    archived_at TIMESTAMP NOT NULL,
    reason VARCHAR(255) NOT NULL,
    format VARCHAR(64) NOT NULL,
    PRIMARY KEY (task_correlation, state_token)
);
CREATE INDEX continuity_memory_history_cleanup ON sennard.continuity_memory_history (archived_at, task_correlation);

CREATE TABLE sennard.continuity_requests (
    task_correlation VARCHAR(255) NOT NULL,
    epoch BIGINT NOT NULL,
    operation_key_hash VARCHAR(255) NOT NULL,
    command_digest VARCHAR(255) NOT NULL,
    result_json ${long_text} NOT NULL,
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (task_correlation, epoch, operation_key_hash)
);
CREATE INDEX continuity_requests_cleanup ON sennard.continuity_requests (created_at, task_correlation, epoch);

CREATE TABLE sennard.continuity_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_correlation VARCHAR(255) NOT NULL,
    epoch BIGINT NOT NULL,
    event VARCHAR(500) NOT NULL, -- event, task_correlation and epoch are one index (continuity_observations_event): 500 + 255 characters and the epoch fit MariaDB's 3072 bytes in utf8mb4
    turn_hash VARCHAR(255),
    outcome VARCHAR(16) NOT NULL,
    observed_at TIMESTAMP NOT NULL,
    PRIMARY KEY (observation_id),
    CONSTRAINT continuity_observations_outcome CHECK (outcome IN ('SUCCEEDED', 'FAILED'))
);
CREATE INDEX continuity_observations_cleanup ON sennard.continuity_observations (observed_at, task_correlation, epoch);
CREATE INDEX continuity_observations_event ON sennard.continuity_observations (event, task_correlation, epoch);
CREATE INDEX continuity_observations_task ON sennard.continuity_observations (task_correlation, epoch, observation_id);

CREATE TABLE sennard.continuity_tombstones (
    task_correlation VARCHAR(255) NOT NULL,
    epoch BIGINT NOT NULL,
    state_token VARCHAR(255) NOT NULL,
    empty_state_token VARCHAR(255) NOT NULL,
    payload_digest VARCHAR(255) NOT NULL,
    purged_at TIMESTAMP NOT NULL,
    PRIMARY KEY (task_correlation, epoch)
);
CREATE INDEX continuity_tombstones_cleanup ON sennard.continuity_tombstones (purged_at, task_correlation, epoch);

-- Replaces VACUUM INTO before a state cleanup (design 3.2): same transaction as the deletion, the row as JSON text made by Java, no dynamic DDL.
CREATE TABLE sennard.continuity_cleanup_backup (
    plan_id VARCHAR(255) NOT NULL,
    table_name VARCHAR(255) NOT NULL,
    row_no BIGINT NOT NULL,
    row_json ${long_text} NOT NULL,
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (plan_id, table_name, row_no)
);

