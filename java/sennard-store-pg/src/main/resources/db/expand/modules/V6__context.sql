-- V6: the shared context layer. admin_log.intent and role_contexts.body are compared byte for byte.
CREATE TABLE sennard.admin_log (
    seq        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    target     VARCHAR(255) NOT NULL,
    intent     ${long_text} NOT NULL,
    credential_id ${long_text} NOT NULL,
    authenticator_data ${long_text} NOT NULL,
    client_data_json ${long_text} NOT NULL,
    signature  ${long_text} NOT NULL,
    record_hash VARCHAR(255) NOT NULL,
    request_id VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (seq)
);

-- A request id signs one record: the records made for a request id are listed here, one row per record, and the UNIQUE key on the request id makes a second record for it fail.
-- (A UNIQUE index over the records that have a request id would be a partial index, which the standard has not.) A record without a request id has no row here.
CREATE TABLE sennard.admin_log_requests (
    seq        BIGINT       NOT NULL,
    request_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (seq),
    CONSTRAINT admin_log_requests_request UNIQUE (request_id),
    CONSTRAINT admin_log_requests_seq FOREIGN KEY (seq) REFERENCES sennard.admin_log (seq)
);

CREATE TABLE sennard.admin_log_archive (
    seq        BIGINT NOT NULL,
    target     VARCHAR(255) NOT NULL,
    intent     ${long_text} NOT NULL,
    credential_id ${long_text} NOT NULL,
    authenticator_data ${long_text} NOT NULL,
    client_data_json ${long_text} NOT NULL,
    signature  ${long_text} NOT NULL,
    record_hash VARCHAR(255) NOT NULL,
    request_id VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    reset_id   BIGINT NOT NULL,
    PRIMARY KEY (reset_id, seq)
);

CREATE TABLE sennard.admin_resets (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reset_of  VARCHAR(255),
    archived  BIGINT NOT NULL,
    at        TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE sennard.admin_proposals (
    id        VARCHAR(255) NOT NULL,
    target    VARCHAR(255) NOT NULL,
    change_text ${long_text} NOT NULL, -- not named change: CHANGE is a reserved word of MariaDB and MySQL
    base_hash VARCHAR(255),
    host      VARCHAR(64)  NOT NULL,
    session_id VARCHAR(512) NOT NULL,
    actor     VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    state     VARCHAR(16) NOT NULL, -- ProposalState: the enum constant's name
    decided_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT admin_proposals_state CHECK (state IN ('PENDING', 'REJECTED', 'APPLIED'))
);

CREATE TABLE sennard.role_contexts (
    role_id   VARCHAR(255) NOT NULL,
    body      ${long_text} NOT NULL,
    state_token VARCHAR(255) NOT NULL,
    digest    VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    PRIMARY KEY (role_id)
);

CREATE TABLE sennard.role_context_history (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_id   VARCHAR(255) NOT NULL,
    body      ${long_text} NOT NULL,
    state_token VARCHAR(255) NOT NULL,
    digest    VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT role_context_history_role FOREIGN KEY (role_id) REFERENCES sennard.role_contexts (role_id) ON DELETE CASCADE
);
CREATE INDEX role_context_history_role ON sennard.role_context_history (role_id, id);

CREATE TABLE sennard.session_seen (
    host      VARCHAR(64)  NOT NULL,
    session_id VARCHAR(512) NOT NULL,
    last_seen_at TIMESTAMP NOT NULL,
    -- A host whose subagent runs its hooks under its own conversation id (a child that is not the root): the root session the child belongs to, set when a tool call
    -- of the child named both. The role binding is the root's, so a hook of the child reads it through this column.
    root_session_id VARCHAR(512),
    PRIMARY KEY (host, session_id)
);

CREATE TABLE sennard.context_deliveries (
    actor_id  VARCHAR(512) NOT NULL,
    global_token VARCHAR(255),
    role      VARCHAR(255),
    role_token VARCHAR(255),
    delivered_at TIMESTAMP NOT NULL,
    PRIMARY KEY (actor_id)
);

CREATE TABLE sennard.jev_keys (
    name      VARCHAR(255) NOT NULL,
    fingerprint VARCHAR(255) NOT NULL,
    sealed    ${long_text} NOT NULL,
    stored_at TIMESTAMP NOT NULL,
    PRIMARY KEY (name)
);

