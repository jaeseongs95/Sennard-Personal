-- V4: JEV and skill usage. The personal edition has no hosted allowance, so there are no budget tables.
CREATE TABLE sennard.jev_usage_daily (
    day        TIMESTAMP        NOT NULL, -- the UTC day: the value at 00:00 UTC
    model_id   VARCHAR(255)     NOT NULL,
    calls      BIGINT NOT NULL,
    input_tokens  BIGINT NOT NULL,
    output_tokens BIGINT NOT NULL,
    estimated_usd DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (day, model_id)
);

-- A host's call id counts once: the calls that have an id are listed here, and the primary key is what makes a second record of the same call fail. (A UNIQUE index over the rows
-- that have an id would be a partial index, which the standard has not.) A call without an id has no row here and is recorded every time.
CREATE TABLE sennard.skill_call_ids (
    host       VARCHAR(64)  NOT NULL,
    session_id VARCHAR(512) NOT NULL,
    call_id    VARCHAR(192) NOT NULL, -- host + session_id + call_id (768 characters) is the longest key MariaDB's InnoDB takes in utf8mb4 (3072 bytes)
    at         TIMESTAMP    NOT NULL,
    PRIMARY KEY (host, session_id, call_id)
);
CREATE INDEX skill_call_ids_at ON sennard.skill_call_ids (at);

-- who made a call: the constant's name of CallerKind (a yes-or-no fact is a name that says what it means, not 0 and 1). A call that has an id refers to its row above (a foreign key
-- over a column that is NULL is not checked, so a call without an id is free of it).
CREATE TABLE sennard.skill_calls (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    at         TIMESTAMP        NOT NULL,
    host       VARCHAR(64)      NOT NULL,
    session_id VARCHAR(512)     NOT NULL,
    skill_id   VARCHAR(255)     NOT NULL,
    caller     VARCHAR(16)      NOT NULL,
    basis      VARCHAR(255)     NOT NULL,
    call_id    VARCHAR(192),
    PRIMARY KEY (id),
    CONSTRAINT skill_calls_caller CHECK (caller IN ('MAIN', 'SUBAGENT')),
    CONSTRAINT skill_calls_call FOREIGN KEY (host, session_id, call_id) REFERENCES sennard.skill_call_ids (host, session_id, call_id)
);
CREATE INDEX skill_calls_at ON sennard.skill_calls (at);

