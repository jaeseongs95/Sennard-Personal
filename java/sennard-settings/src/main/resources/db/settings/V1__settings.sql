-- V1: Sennard's own settings store (an H2 file database, never the business database): the passkey public keys, the signed admin records of the time before the
-- business database is linked, and the settings of that link when the admin page made them (the URL, the account, the file that holds its password, the user's JDBC
-- driver and how the link is protected; never the password). A business database named by sennard.store.database.* wins over the link settings.
-- No CHECK lists the allowed values of a column (an IN list or an OR chain): H2 2.4.240 refused correct rows of an open database in such a CHECK, so the closed
-- sets (state, algorithm) are Java enums and the code checks them before it writes and when it reads. Time columns are TIMESTAMP holding UTC.
CREATE TABLE sennard.passkey_credentials (
    credential_id VARCHAR(200)  NOT NULL,
    public_key    VARCHAR(4000) NOT NULL,
    algorithm     VARCHAR(16)   NOT NULL, -- PasskeyAlgorithm: the enum constant's name
    label         VARCHAR(255)  NOT NULL,
    state         VARCHAR(16)   NOT NULL, -- PasskeyState: the enum constant's name
    registered_at TIMESTAMP     NOT NULL,
    revoked_at    TIMESTAMP,
    PRIMARY KEY (credential_id)
);

CREATE TABLE sennard.pre_link_admin_records (
    seq                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    target             VARCHAR(255) NOT NULL,
    intent             CLOB         NOT NULL,
    credential_id      VARCHAR(200) NOT NULL,
    authenticator_data CLOB         NOT NULL,
    client_data_json   CLOB         NOT NULL,
    signature          CLOB         NOT NULL,
    record_hash        VARCHAR(255) NOT NULL,
    request_id         VARCHAR(255),
    created_at         TIMESTAMP    NOT NULL,
    PRIMARY KEY (seq),
    -- A request id signs one record; a record without one has NULL, which a UNIQUE constraint does not compare.
    CONSTRAINT pre_link_admin_records_request UNIQUE (request_id)
);

-- The records the admin reset moved out of the log (the sequence number goes on counting, so it is the key here too).
CREATE TABLE sennard.pre_link_admin_records_archive (
    seq                BIGINT       NOT NULL,
    target             VARCHAR(255) NOT NULL,
    intent             CLOB         NOT NULL,
    credential_id      VARCHAR(200) NOT NULL,
    authenticator_data CLOB         NOT NULL,
    client_data_json   CLOB         NOT NULL,
    signature          CLOB         NOT NULL,
    record_hash        VARCHAR(255) NOT NULL,
    request_id         VARCHAR(255),
    created_at         TIMESTAMP    NOT NULL,
    archived_at        TIMESTAMP    NOT NULL,
    PRIMARY KEY (seq)
);

-- One row (the code writes 1) once the business database was ready for the first time: the section of the admin log before the link takes no more records.
CREATE TABLE sennard.pre_link_closed (
    closed_id INTEGER   NOT NULL,
    closed_at TIMESTAMP NOT NULL,
    PRIMARY KEY (closed_id)
);

CREATE TABLE sennard.database_link (
    link_id      INTEGER       NOT NULL, -- one link per installation: the code writes 1
    driver_path  VARCHAR(1024) NOT NULL, -- a jar or a folder of jars
    jdbc_url     VARCHAR(2048) NOT NULL,
    db_user      VARCHAR(255)  NOT NULL,
    password_ref VARCHAR(1024) NOT NULL, -- the file that holds the password: the password itself is nowhere in this database
    tls_policy   VARCHAR(32)   NOT NULL, -- DatabaseTls: the enum constant's name
    saved_at     TIMESTAMP     NOT NULL,
    PRIMARY KEY (link_id)
);
